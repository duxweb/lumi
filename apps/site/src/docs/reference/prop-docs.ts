export function propDoc(component: string, prop: string): PropDoc | undefined {
  const own = COMPONENT_PROPS[component]?.[prop]
  const common = COMMON_PROPS[prop]
  if (!own)
    return common
  return { text: own.text, default: own.default ?? common?.default }
}
